#!/usr/bin/env python3
"""Generate the operation layer of an Arianet SDK from specs/*.json.

Usage:
    python3 codegen/generate.py            # write the generated files
    python3 codegen/generate.py --check    # exit 1 if they are out of date

The target language comes from codegen/language (go, python, php or js). The
script only needs the Python standard library (plus gofmt for Go), reads the
specs committed under specs/ (refresh them with codegen/fetch_specs.py) and
writes one method per operation plus the error-code constants. The
hand-written runtime (auth, retries, errors) lives next to it and is never
touched by this script.
"""

from __future__ import annotations

import json
import keyword
import pathlib
import re
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONFIG = json.loads((ROOT / "codegen" / "services.json").read_text())
LANGUAGE = (ROOT / "codegen" / "language").read_text().strip()
METHODS = ["get", "post", "put", "patch", "delete"]
HEADER = "Code generated by codegen/generate.py from specs/*.json. DO NOT EDIT."

# ─── Spec → intermediate representation ──────────────────────────────────────


def words(name: str) -> list[str]:
    """Split an identifier into lower-case words: listElasticIPs → list elastic ips."""
    s = re.sub(r"[^A-Za-z0-9]+", "_", name)
    s = re.sub(r"([A-Z]{2,})s(?=[A-Z0-9_]|$)", lambda m: "_" + m.group(1).lower() + "s", s)
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", s)
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s)
    out = []
    for w in s.lower().split("_"):
        if w:
            out.extend(split_acronyms(w))
    return out


ACRONYMS = ["ipv4", "ipv6", "ip", "dns", "ptr", "ssh", "ssl", "tls", "api", "url", "nat", "vps", "sms", "os", "lb", "id", "cpu", "ram"]


def split_acronyms(word: str) -> list[str]:
    """'ipdns' → ['ip', 'dns'] when the word is made only of known acronyms."""
    if word in ACRONYMS:
        return [word]
    for a in ACRONYMS:
        if word.startswith(a) and len(word) > len(a):
            rest = split_acronyms(word[len(a):])
            if all(r in ACRONYMS for r in rest):
                return [a] + rest
    return [word]


def snake(name: str) -> str:
    return "_".join(words(name))


def lower_camel(name: str) -> str:
    ws = words(name)
    return ws[0] + "".join(w.capitalize() for w in ws[1:])


def upper_camel(name: str) -> str:
    return "".join(w.capitalize() for w in words(name))


class Spec:
    def __init__(self, doc: dict):
        self.doc = doc

    def resolve(self, obj):
        seen = 0
        while isinstance(obj, dict) and "$ref" in obj:
            ref = obj["$ref"]
            if not ref.startswith("#/"):
                raise ValueError(f"external $ref not supported: {ref}")
            node = self.doc
            for part in ref[2:].split("/"):
                node = node[part.replace("~1", "/").replace("~0", "~")]
            obj = node
            seen += 1
            if seen > 50:
                raise ValueError(f"$ref loop at {ref}")
        return obj

    def scalar_type(self, schema) -> str:
        s = self.resolve(schema or {})
        t = s.get("type")
        if isinstance(t, list):
            t = next((x for x in t if x != "null"), "string")
        if not t:
            for key in ("anyOf", "oneOf", "allOf"):
                for sub in s.get(key, []):
                    st = self.scalar_type(sub)
                    if st:
                        return st
            return "string"
        if t == "array":
            return "array:" + self.scalar_type(s.get("items", {}))
        if t in ("integer", "number", "boolean", "string"):
            return t
        return "string"


def first_line(text: str | None) -> str:
    if not text:
        return ""
    for line in text.strip().splitlines():
        line = line.strip()
        if line:
            return line
    return ""


def build_ir() -> list[dict]:
    excluded = set(CONFIG.get("exclude", []))
    services = []
    for svc in CONFIG["services"]:
        doc = json.loads((ROOT / "specs" / f"{svc['key']}.json").read_text())
        spec = Spec(doc)
        names = CONFIG.get("operation_names", {}).get(svc["key"], {})
        ops = []
        used = set()
        for path in sorted(doc["paths"]):
            item = spec.resolve(doc["paths"][path])
            common = item.get("parameters", [])
            for method in METHODS:
                if method not in item:
                    continue
                route = f"{method.upper()} {path}"
                if route in excluded:
                    continue
                op = item[method]
                op_id = names.get(route) or op.get("operationId") or synth_name(method, path)
                if op_id in used:
                    op_id = op_id + method.capitalize()
                used.add(op_id)

                merged: dict[tuple[str, str], dict] = {}
                for p in common + op.get("parameters", []):
                    p = spec.resolve(p)
                    merged[(p["name"], p["in"])] = p
                template_names = re.findall(r"{([^}]+)}", path)
                path_params = []
                for tn in template_names:
                    p = merged.get((tn, "path"), {"name": tn, "schema": {"type": "string"}})
                    path_params.append({"name": tn, "type": spec.scalar_type(p.get("schema")), "description": first_line(p.get("description"))})
                query = []
                idempotent = False
                for (name, where), p in merged.items():
                    if where == "query":
                        query.append({
                            "name": name,
                            "type": spec.scalar_type(p.get("schema")),
                            "required": bool(p.get("required")),
                            "description": first_line(p.get("description")),
                        })
                    elif where == "header" and name.lower() == "idempotency-key":
                        idempotent = True
                body = None
                if "requestBody" in op:
                    rb = spec.resolve(op["requestBody"])
                    body = {"required": bool(rb.get("required")), "content": sorted(rb.get("content", {}).keys())}
                summary = first_line(op.get("summary")) or first_line(op.get("description")) or route
                ops.append({
                    "id": op_id,
                    "method": method.upper(),
                    "path": path,
                    "segments": split_path(svc["prefix"] + path),
                    "path_params": path_params,
                    "query": query,
                    "body": body,
                    "idempotent": idempotent,
                    "summary": summary,
                    "deprecated": bool(op.get("deprecated")),
                })
        services.append({**svc, "operations": ops})
    return services


def synth_name(method: str, path: str) -> str:
    parts = [p for p in path.strip("/").split("/") if p and not p.startswith("{")]
    verb = {"get": "get", "post": "create", "put": "update", "patch": "update", "delete": "delete"}[method]
    return verb + "".join(upper_camel(p) for p in parts)


def split_path(path: str) -> list[tuple[str, str]]:
    """'/servers/{id}/actions' → [('lit','/servers/'),('param','id'),('lit','/actions')]."""
    out = []
    pos = 0
    for m in re.finditer(r"{([^}]+)}", path):
        if m.start() > pos:
            out.append(("lit", path[pos:m.start()]))
        out.append(("param", m.group(1)))
        pos = m.end()
    if pos < len(path):
        out.append(("lit", path[pos:]))
    return out


def collect_error_codes() -> list[str]:
    codes: set[str] = set()

    def walk(node):
        if isinstance(node, dict):
            for k, v in node.items():
                if k == "x-error-codes" and isinstance(v, dict):
                    for lst in v.values():
                        codes.update(c for c in lst if isinstance(c, str))
                walk(v)
        elif isinstance(node, list):
            for v in node:
                walk(v)

    for svc in CONFIG["services"]:
        doc = json.loads((ROOT / "specs" / f"{svc['key']}.json").read_text())
        walk(doc)
        err = doc.get("components", {}).get("schemas", {}).get("Error", {})
        props = err.get("properties", {})
        code_schema = props.get("code") or props.get("error", {}).get("properties", {}).get("code", {})
        codes.update(c for c in code_schema.get("enum", []) if isinstance(c, str))
        codes.update(re.findall(r"\b([a-z][a-z0-9_]+) \(\d{3}\)", code_schema.get("description", "")))
    return sorted({c.lower() for c in codes if re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", c)})


def service_classname(key: str) -> str:
    special = {"regional_vps": "RegionalVPS", "sms": "SMS"}
    return special.get(key, upper_camel(key))


# ─── Go ──────────────────────────────────────────────────────────────────────

GO_INITIALISMS = {
    "id", "ip", "url", "api", "http", "https", "dns", "ssl", "os", "cpu", "ram", "ssh", "vps", "sms",
    "uuid", "ipv4", "ipv6", "lb", "nat", "json", "tls", "ttl", "cidr", "mac", "vlan", "ptr", "uri", "sni",
}
GO_KEYWORDS = {
    "break", "case", "chan", "const", "continue", "default", "defer", "else", "fallthrough", "for", "func",
    "go", "goto", "if", "import", "interface", "map", "package", "range", "return", "select", "struct",
    "switch", "type", "var", "ctx", "params", "body", "opts", "s", "string", "int", "bool", "error",
}


def go_word(w: str) -> str:
    if w in GO_INITIALISMS:
        return w.upper()
    if w == "ips":
        return "IPs"
    return w.capitalize()


def go_exported(name: str) -> str:
    out = "".join(go_word(w) for w in words(name))
    if out and out[0].isdigit():
        out = "N" + out
    return out


def go_local(name: str) -> str:
    ws = words(name)
    out = ws[0] + "".join(go_word(w) for w in ws[1:])
    if out in GO_KEYWORDS:
        out += "Param"
    return out


def go_type(t: str) -> str:
    if t.startswith("array:"):
        return "[]" + go_type(t[6:])
    return {"integer": "int64", "number": "float64", "boolean": "bool"}.get(t, "string")


def go_comment(text: str) -> str:
    return text.replace("\n", " ").replace("*/", "* /")


def emit_go(services: list[dict], codes: list[str]) -> dict[str, str]:
    files = {}
    lines = [f"// {HEADER}", "", "package arianet", ""]
    lines += ['import (', '\t"context"', '\t"net/url"', ')', ""]
    lines += ["var (", "\t_ = url.Values{}", "\t_ context.Context", ")", ""]
    lines.append("// services wires every generated API group to the client.")
    lines.append("func (c *Client) initServices() {")
    for svc in services:
        lines.append(f"\tc.{service_classname(svc['key'])} = &{service_classname(svc['key'])}Service{{service{{client: c}}}}")
    lines.append("}")
    lines.append("")
    files["services_gen.go"] = "\n".join(lines) + "\n"

    for svc in services:
        cls = service_classname(svc["key"])
        out = [f"// {HEADER}", "", "package arianet", ""]
        out += ['import (', '\t"context"', '\t"net/url"', ')', ""]
        out += ["var _ = url.Values{}", ""]
        out.append(f"// {cls}Service calls the {svc['title']} (`{svc['prefix']}`).")
        out.append(f"type {cls}Service struct{{ service }}")
        out.append("")
        out.append(f"// WithRegion returns a copy of the service whose requests go to region")
        out.append("// (sent as the Arianet-Region header). An empty region means the default.")
        out.append(f"func (s *{cls}Service) WithRegion(region string) *{cls}Service {{")
        out.append(f"\treturn &{cls}Service{{s.withRegion(region)}}")
        out.append("}")
        out.append("")
        for op in svc["operations"]:
            name = go_exported(op["id"])
            params_type = f"{cls}{name}Params"
            args = ["ctx context.Context"]
            path_expr = []
            local_names = {}
            for pp in op["path_params"]:
                local = go_local(pp["name"])
                local_names[pp["name"]] = local
                gt = go_type(pp["type"])
                args.append(f"{local} {gt}")
            for kind, val in op["segments"]:
                if kind == "lit":
                    path_expr.append(json.dumps(val))
                else:
                    path_expr.append(f"pathSegment({local_names[val]})")
            if op["body"] is not None:
                args.append("body any")
            if op["query"]:
                args.append(f"params *{params_type}")
            args.append("opts ...RequestOption")
            if op["query"]:
                out.append(f"// {params_type} holds the query parameters of {cls}Service.{name}.")
                out.append(f"type {params_type} struct {{")
                for q in op["query"]:
                    if q["description"]:
                        out.append(f"\t// {go_comment(q['description'])}")
                    out.append(f"\t{go_exported(q['name'])} *{go_type(q['type'])}")
                out.append("}")
                out.append("")
                out.append(f"func (p *{params_type}) values() url.Values {{")
                out.append("\tv := url.Values{}")
                out.append("\tif p == nil {")
                out.append("\t\treturn v")
                out.append("\t}")
                for q in op["query"]:
                    field = go_exported(q["name"])
                    out.append(f"\tif p.{field} != nil {{")
                    if q["type"].startswith("array:"):
                        out.append(f"\t\tfor _, item := range *p.{field} {{")
                        out.append(f"\t\t\tv.Add({json.dumps(q['name'])}, queryValue(item))")
                        out.append("\t\t}")
                    else:
                        out.append(f"\t\tv.Set({json.dumps(q['name'])}, queryValue(*p.{field}))")
                    out.append("\t}")
                out.append("\treturn v")
                out.append("}")
                out.append("")
            out.append(f"// {name} calls {op['method']} {op['path']}.")
            out.append("//")
            out.append(f"// {go_comment(op['summary'])}")
            if op["idempotent"]:
                out.append("//")
                out.append("// The request carries an Idempotency-Key (generated when none is given with")
                out.append("// WithIdempotencyKey), so it is retried safely after a network error or a 5xx.")
            if op["deprecated"]:
                out.append("//")
                out.append("// Deprecated: the API marks this operation as deprecated.")
            out.append(f"func (s *{cls}Service) {name}({', '.join(args)}) (*Response, error) {{")
            query_expr = "params.values()" if op["query"] else "nil"
            body_expr = "body" if op["body"] is not None else "nil"
            full_path = " + ".join(path_expr)
            idem = "true" if op["idempotent"] else "false"
            out.append(f"\treturn s.do(ctx, {json.dumps(op['method'])}, {full_path}, {query_expr}, {body_expr}, {idem}, opts)")
            out.append("}")
            out.append("")
        files[f"{svc['key']}_gen.go"] = "\n".join(out) + "\n"

    out = [f"// {HEADER}", "", "package arianet", ""]
    out.append("// Stable error codes the Arianet APIs answer with, lower-cased. APIError.Code")
    out.append("// is always lower-case, so compare it with these constants.")
    out.append("const (")
    for code in codes:
        out.append(f"\tErrorCode{go_exported(code)} = {json.dumps(code)}")
    out.append(")")
    files["error_codes_gen.go"] = "\n".join(out) + "\n"

    gofmt = shutil.which("gofmt")
    if not gofmt:
        raise SystemExit("gofmt not found in PATH")
    for name, text in files.items():
        res = subprocess.run([gofmt], input=text, capture_output=True, text=True)
        if res.returncode != 0:
            raise SystemExit(f"gofmt failed on {name}:\n{res.stderr}")
        files[name] = res.stdout
    return files


# ─── Python ──────────────────────────────────────────────────────────────────

PY_RESERVED = set(keyword.kwlist) | {"self", "body", "headers", "idempotency_key", "timeout", "type", "id_"}


def py_ident(name: str) -> str:
    out = snake(name) or "param"
    if out[0].isdigit():
        out = "n_" + out
    if out in PY_RESERVED and out not in ("id", "type"):
        out += "_"
    return out


def py_type(t: str) -> str:
    if t.startswith("array:"):
        return f"Sequence[{py_type(t[6:])}]"
    return {"integer": "int", "number": "float", "boolean": "bool"}.get(t, "str")


def py_doc(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"""', "'''")


def emit_python(services: list[dict], codes: list[str]) -> dict[str, str]:
    out = [f'"""{HEADER}"""', "", "from __future__ import annotations", "", "from typing import Any, Mapping, Optional, Sequence", ""]
    out.append("from ._base import Service, path_segment")
    out.append("")
    out.append('__all__ = [' + ", ".join(json.dumps(service_classname(s["key"]) + "Service") for s in services) + "]")
    out.append("")
    for svc in services:
        cls = service_classname(svc["key"]) + "Service"
        out.append("")
        out.append(f"class {cls}(Service):")
        out.append(f'    """{py_doc(svc["title"])} (``{svc["prefix"]}``)."""')
        out.append("")
        out.append(f"    _prefix = {json.dumps(svc['prefix'])}")
        for op in svc["operations"]:
            name = snake(op["id"])
            if keyword.iskeyword(name):
                name += "_"
            sig = ["self"]
            taken = set()
            locals_ = {}
            for pp in op["path_params"]:
                ident = py_ident(pp["name"])
                locals_[pp["name"]] = ident
                taken.add(ident)
                sig.append(f"{ident}: {'int | str' if pp['type'] == 'integer' else 'str'}")
            if op["body"] is not None:
                sig.append("body: Any" if op["body"]["required"] else "body: Any = None")
            sig.append("*")
            query_map = []
            for q in op["query"]:
                ident = py_ident(q["name"])
                if ident in taken:
                    ident += "_query"
                taken.add(ident)
                query_map.append((q["name"], ident))
                sig.append(f"{ident}: Optional[{py_type(q['type'])}] = None")
            sig.append("idempotency_key: Optional[str] = None")
            sig.append("headers: Optional[Mapping[str, str]] = None")
            out.append("")
            out.append(f"    def {name}(")
            for s in sig:
                out.append(f"        {s},")
            out.append("    ) -> Any:")
            out.append(f'        """{py_doc(op["summary"])}')
            out.append("")
            out.append(f"        ``{op['method']} {op['path']}``")
            if op["idempotent"]:
                out.append("")
                out.append("        Sent with an Idempotency-Key (generated when ``idempotency_key`` is")
                out.append("        not given), so it is retried safely after a network error or a 5xx.")
            if op["deprecated"]:
                out.append("")
                out.append("        Deprecated by the API.")
            out.append('        """')
            parts = []
            for kind, val in op["segments"]:
                parts.append(json.dumps(val) if kind == "lit" else f"path_segment({locals_[val]})")
            path_expr = " + ".join(parts) if parts else '""'
            query_expr = "{" + ", ".join(f"{json.dumps(n)}: {i}" for n, i in query_map) + "}" if query_map else "None"
            out.append("        return self._request(")
            out.append(f"            {json.dumps(op['method'])},")
            out.append(f"            {path_expr},")
            out.append(f"            query={query_expr},")
            out.append(f"            body={'body' if op['body'] is not None else 'None'},")
            out.append(f"            idempotent={'True' if op['idempotent'] else 'False'},")
            out.append("            idempotency_key=idempotency_key,")
            out.append("            headers=headers,")
            out.append("        )")
        out.append("")
    files = {"src/arianet/_services.py": "\n".join(out)}

    lines = [f'"""{HEADER}"""', "", "", "class ErrorCode:", '    """Stable error codes the Arianet APIs answer with, lower-cased.', "", "    ``APIError.code`` is always lower-case, so compare it with these constants.", '    """', ""]
    for code in codes:
        lines.append(f"    {snake(code).upper()} = {json.dumps(code)}")
    files["src/arianet/_error_codes.py"] = "\n".join(lines) + "\n"

    lines = [f'"""{HEADER}"""', "", "from __future__ import annotations", "", "from typing import TYPE_CHECKING", "", "from ._services import " + ", ".join(service_classname(s["key"]) + "Service" for s in services), "", "if TYPE_CHECKING:", "    from ._client import Client", "", "", "def attach_services(client: Client) -> None:"]
    for svc in services:
        lines.append(f"    client.{svc['key']} = {service_classname(svc['key'])}Service(client)")
    files["src/arianet/_wiring.py"] = "\n".join(lines) + "\n"
    return files


# ─── PHP ─────────────────────────────────────────────────────────────────────

PHP_RESERVED_VARS = {"this", "query", "options", "body"}


def php_var(name: str) -> str:
    out = lower_camel(name) or "param"
    if out[0].isdigit():
        out = "n" + out
    if out in PHP_RESERVED_VARS:
        out += "Param"
    return out


def php_type(t: str) -> str:
    if t.startswith("array:"):
        return "list<" + php_type(t[6:]) + ">"
    return {"integer": "int", "number": "float", "boolean": "bool"}.get(t, "string")


def php_doc(text: str) -> str:
    return text.replace("*/", "* /")


def emit_php(services: list[dict], codes: list[str]) -> dict[str, str]:
    files = {}
    for svc in services:
        cls = service_classname(svc["key"]) + "Service"
        out = ["<?php", "", f"// {HEADER}", "", "declare(strict_types=1);", "", "namespace Arianet\\Service;", ""]
        out.append("/**")
        out.append(f" * {php_doc(svc['title'])} (`{svc['prefix']}`).")
        out.append(" */")
        out.append(f"final class {cls} extends AbstractService")
        out.append("{")
        out.append(f"    protected const PREFIX = '{svc['prefix']}';")
        for op in svc["operations"]:
            name = lower_camel(op["id"])
            params = []
            doc = ["    /**", f"     * {php_doc(op['summary'])}", "     *", f"     * `{op['method']} {op['path']}`"]
            if op["idempotent"]:
                doc += ["     *", "     * Sent with an Idempotency-Key (generated when `idempotency_key` is not in", "     * \\$options), so it is retried safely after a network error or a 5xx."]
            if op["deprecated"]:
                doc += ["     *", "     * @deprecated The API marks this operation as deprecated."]
            doc.append("     *")
            locals_ = {}
            for pp in op["path_params"]:
                var = php_var(pp["name"])
                locals_[pp["name"]] = var
                t = "int|string" if pp["type"] == "integer" else "string"
                params.append(f"{t} ${var}")
                doc.append(f"     * @param {t} ${var}")
            if op["body"] is not None:
                params.append("mixed $body" if op["body"]["required"] else "mixed $body = null")
                doc.append("     * @param mixed $body JSON request body (array or object)")
            if op["query"]:
                shape = ", ".join(f"'{q['name']}'?: {php_type(q['type'])}" for q in op["query"])
                params.append("array $query = []")
                doc.append(f"     * @param array{{{shape}}} $query")
            params.append("array $options = []")
            doc.append("     * @param array{idempotency_key?: string, headers?: array<string, string>, region?: string} $options")
            doc.append("     * @return mixed The decoded JSON response")
            doc.append("     */")
            parts = []
            for kind, val in op["segments"]:
                parts.append("'" + val.replace("\\", "\\\\").replace("'", "\\'") + "'" if kind == "lit" else f"self::segment(${locals_[val]})")
            path_expr = " . ".join(parts) if parts else "''"
            out.append("")
            out += doc
            out.append(f"    public function {name}({', '.join(params)}): mixed")
            out.append("    {")
            q = "$query" if op["query"] else "[]"
            b = "$body" if op["body"] is not None else "null"
            idem = "true" if op["idempotent"] else "false"
            out.append(f"        return $this->send('{op['method']}', {path_expr}, {q}, {b}, $options, {idem});")
            out.append("    }")
        out.append("}")
        files[f"src/Service/{cls}.php"] = "\n".join(out) + "\n"

    out = ["<?php", "", f"// {HEADER}", "", "declare(strict_types=1);", "", "namespace Arianet;", ""]
    out += ["/**", " * Stable error codes the Arianet APIs answer with, lower-cased.", " * ApiException::getErrorCode() is always lower-case, so compare it with these.", " */", "final class ErrorCode", "{"]
    for code in codes:
        out.append(f"    public const {snake(code).upper()} = '{code}';")
    out.append("}")
    files["src/ErrorCode.php"] = "\n".join(out) + "\n"

    out = ["<?php", "", f"// {HEADER}", "", "declare(strict_types=1);", "", "namespace Arianet;", ""]
    out += ["/**", " * The API groups of a Client, one property per service.", " */", "trait Services", "{"]
    for svc in services:
        cls = service_classname(svc["key"]) + "Service"
        out.append(f"    public readonly Service\\{cls} ${lower_camel(svc['key'])};")
    out.append("")
    out.append("    private function initServices(): void")
    out.append("    {")
    for svc in services:
        cls = service_classname(svc["key"]) + "Service"
        out.append(f"        $this->{lower_camel(svc['key'])} = new Service\\{cls}($this);")
    out.append("    }")
    out.append("}")
    files["src/Services.php"] = "\n".join(out) + "\n"
    return files


# ─── TypeScript ──────────────────────────────────────────────────────────────

TS_RESERVED = {
    "break", "case", "catch", "class", "const", "continue", "debugger", "default", "delete", "do", "else",
    "enum", "export", "extends", "false", "finally", "for", "function", "if", "import", "in", "instanceof",
    "new", "null", "return", "super", "switch", "this", "throw", "true", "try", "typeof", "var", "void",
    "while", "with", "yield", "let", "static", "implements", "interface", "package", "private", "protected",
    "public", "await", "query", "options", "body",
}


def ts_ident(name: str) -> str:
    out = lower_camel(name) or "param"
    if out[0].isdigit():
        out = "n" + out
    if out in TS_RESERVED:
        out += "Param"
    return out


def ts_type(t: str) -> str:
    if t.startswith("array:"):
        return ts_type(t[6:]) + "[]"
    return {"integer": "number", "number": "number", "boolean": "boolean"}.get(t, "string")


def ts_key(name: str) -> str:
    return name if re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", name) else json.dumps(name)


def emit_js(services: list[dict], codes: list[str]) -> dict[str, str]:
    out = [f"// {HEADER}", "", 'import { Service, pathSegment, type RequestOptions } from "../service.js";', ""]
    for svc in services:
        cls = service_classname(svc["key"]) + "Service"
        prefix_cls = service_classname(svc["key"])
        for op in svc["operations"]:
            if op["query"]:
                out.append(f"/** Query parameters of `{cls}.{lower_camel(op['id'])}`. */")
                out.append(f"export interface {prefix_cls}{upper_camel(op['id'])}Query {{")
                for q in op["query"]:
                    if q["description"]:
                        out.append(f"  /** {q['description'].replace('*/', '* /')} */")
                    out.append(f"  {ts_key(q['name'])}?: {ts_type(q['type'])};")
                out.append("}")
                out.append("")
        out.append(f"/** {svc['title']} (`{svc['prefix']}`). */")
        out.append(f"export class {cls} extends Service {{")
        out.append(f"  protected readonly prefix = {json.dumps(svc['prefix'])};")
        for op in svc["operations"]:
            name = lower_camel(op["id"])
            params = []
            locals_ = {}
            for pp in op["path_params"]:
                ident = ts_ident(pp["name"])
                locals_[pp["name"]] = ident
                params.append(f"{ident}: {'number | string' if pp['type'] == 'integer' else 'string'}")
            if op["body"] is not None:
                params.append("body: unknown" if op["body"]["required"] else "body?: unknown")
            if op["query"]:
                params.append(f"query?: {prefix_cls}{upper_camel(op['id'])}Query")
            params.append("options?: RequestOptions")
            parts = []
            for kind, val in op["segments"]:
                parts.append(json.dumps(val) if kind == "lit" else f"pathSegment({locals_[val]})")
            path_expr = " + ".join(parts) if parts else '""'
            out.append("")
            out.append("  /**")
            out.append(f"   * {op['summary'].replace('*/', '* /')}")
            out.append("   *")
            out.append(f"   * `{op['method']} {op['path']}`")
            if op["idempotent"]:
                out.append("   *")
                out.append("   * Sent with an Idempotency-Key (generated when `options.idempotencyKey` is not")
                out.append("   * given), so it is retried safely after a network error or a 5xx.")
            if op["deprecated"]:
                out.append("   *")
                out.append("   * @deprecated The API marks this operation as deprecated.")
            out.append("   */")
            out.append(f"  {name}({', '.join(params)}): Promise<any> {{")
            q = "query as Record<string, unknown> | undefined" if op["query"] else "undefined"
            b = "body" if op["body"] is not None else "undefined"
            out.append(f"    return this.send({json.dumps(op['method'])}, {path_expr}, {q}, {b}, options, {'true' if op['idempotent'] else 'false'});")
            out.append("  }")
        out.append("}")
        out.append("")
    files = {"src/generated/services.ts": "\n".join(out)}

    out = [f"// {HEADER}", "", "/**", " * Stable error codes the Arianet APIs answer with, lower-cased.", " * `APIError.code` is always lower-case, so compare it with these.", " */", "export const ErrorCode = {"]
    for code in codes:
        out.append(f"  {snake(code).upper()}: {json.dumps(code)},")
    out.append("} as const;")
    out.append("")
    out.append("export type ErrorCode = (typeof ErrorCode)[keyof typeof ErrorCode];")
    files["src/generated/errorCodes.ts"] = "\n".join(out) + "\n"

    out = [f"// {HEADER}", "", "import type { Transport } from \"../service.js\";", "import {"]
    for svc in services:
        out.append(f"  {service_classname(svc['key'])}Service,")
    out.append('} from "./services.js";')
    out.append("")
    out.append("/** The API groups of a Client, one property per service. */")
    out.append("export class Services {")
    for svc in services:
        out.append(f"  readonly {lower_camel(svc['key'])}: {service_classname(svc['key'])}Service;")
    out.append("")
    out.append("  constructor(transport: Transport) {")
    for svc in services:
        out.append(f"    this.{lower_camel(svc['key'])} = new {service_classname(svc['key'])}Service(transport);")
    out.append("  }")
    out.append("}")
    files["src/generated/clientServices.ts"] = "\n".join(out) + "\n"
    return files


EMITTERS = {"go": emit_go, "python": emit_python, "php": emit_php, "js": emit_js}


def main() -> int:
    check = "--check" in sys.argv[1:]
    services = build_ir()
    files = EMITTERS[LANGUAGE](services, collect_error_codes())
    stale = []
    for rel, text in sorted(files.items()):
        path = ROOT / rel
        current = path.read_text() if path.exists() else None
        if current == text:
            continue
        stale.append(rel)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    total = sum(len(s["operations"]) for s in services)
    if check:
        if stale:
            print("generated files are out of date, run python3 codegen/generate.py:\n  " + "\n  ".join(stale), file=sys.stderr)
            return 1
        print(f"generated code is up to date ({total} operations)")
        return 0
    print(f"{LANGUAGE}: {total} operations, {len(stale)} file(s) written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
